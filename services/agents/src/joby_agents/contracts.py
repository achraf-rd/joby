"""Nest <-> Python contracts (ARCHITECTURE §5).

Source of truth: these models are exported to OpenAPI and turned into
TypeScript types in packages/contracts. Never hand-maintain them twice.
Every payload carries `version`.
"""

import enum
import uuid
from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, Field

CONTRACT_VERSION = 1


class RunType(enum.StrEnum):
    discover_and_apply = "discover_and_apply"


class RunStatus(enum.StrEnum):
    queued = "queued"
    running = "running"
    awaiting_approval = "awaiting_approval"
    completed = "completed"
    failed = "failed"
    cancelled = "cancelled"


class StartRunRequest(BaseModel):
    version: Literal[1] = 1
    run_id: uuid.UUID = Field(description="Generated by Nest.")
    tenant_id: uuid.UUID
    user_id: uuid.UUID
    type: RunType
    input: dict[str, Any] = Field(default_factory=dict)
    idempotency_key: str = Field(min_length=1, max_length=255)


class RunAccepted(BaseModel):
    run_id: uuid.UUID
    status: RunStatus


class DecisionAction(enum.StrEnum):
    approve = "approve"
    edit = "edit"
    reject = "reject"


class Decision(BaseModel):
    action: DecisionAction
    edits: dict[str, Any] | None = None


class ResumeRunRequest(BaseModel):
    version: Literal[1] = 1
    decisions: dict[str, Decision] = Field(description="offer_id -> decision")


class RunStatusResponse(BaseModel):
    run_id: uuid.UUID
    status: RunStatus
    attempts: int
    heartbeat_at: datetime | None
    error: str | None
    last_seq: int = Field(description="Highest event seq written to the outbox, 0 if none.")


class RunEventType(enum.StrEnum):
    step_started = "step_started"
    step_completed = "step_completed"
    offer_scored = "offer_scored"
    draft_ready = "draft_ready"
    awaiting_approval = "awaiting_approval"
    application_submitted = "application_submitted"
    usage = "usage"
    failed = "failed"
    completed = "completed"


class RunEvent(BaseModel):
    version: Literal[1] = 1
    run_id: uuid.UUID
    seq: int = Field(ge=1)
    type: RunEventType
    step: str | None = None
    data: dict[str, Any] = Field(default_factory=dict)
    ts: datetime


class RunEventBatch(BaseModel):
    events: list[RunEvent]


class HealthResponse(BaseModel):
    status: Literal["ok", "error"]
    database: Literal["up", "down"]
